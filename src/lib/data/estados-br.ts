export function getEstado(slug: string): Estado | undefined {
  return ESTADOS_BR.find((e) => e.slug === slug);
}

export function getAllEstadoSlugs(): string[] {
  return ESTADOS_BR.map((e) => e.slug);
}

export function getEstadosVizinhos(uf: string): Estado[] {
  // Simplificado: retorna 4 outros estados aleatórios da mesma região.
  const target = ESTADOS_BR.find((e) => e.uf === uf);
  if (!target) return [];
  return ESTADOS_BR
    .filter((e) => e.uf !== uf && e.regiao === target.regiao)
    .slice(0, 4);
}
